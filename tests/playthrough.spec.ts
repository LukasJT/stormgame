import { expect, test, type Page } from '@playwright/test'

async function completeStarterFixture(page: Page) {
  await page.evaluate(() => {
    const played = ['Tornado', 'Hurricane', 'Blizzard', 'Thunderstorm', 'Wildfire', 'Flooding', 'Dust Storm']
    localStorage.setItem('stormwake.records', JSON.stringify(Object.fromEntries(played.map(event => [event, { score: 0, deaths: 0 }]))))
  })
}

async function openMap(page: Page, weather = 'Hurricane', difficulty = 'Normal') {
  if (weather !== 'Tornado') await completeStarterFixture(page)
  await page.getByRole('button', { name: 'Play', exact: true }).click()
  await page.getByRole('button', { name: weather, exact: true }).click()
  await page.getByRole('button', { name: new RegExp(`^${difficulty} `) }).click()
  await page.getByRole('button', { name: 'Play', exact: true }).click()
}

async function dropAt(page: Page, lat: number, lon: number) {
  await page.getByText('Enter coordinates', { exact: true }).click()
  await page.getByRole('spinbutton', { name: 'Latitude' }).fill(String(lat))
  await page.getByRole('spinbutton', { name: 'Longitude' }).fill(String(lon))
  await page.getByRole('button', { name: 'Set drop point' }).click()
}

